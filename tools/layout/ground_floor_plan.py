#!/usr/bin/env python3
"""План первого этажа (проект на утверждение автора). Вывод: docs/assets/ground_floor_plan.png
Север — вверх. Камера W2 стоит за стойкой у её восточного конца и смотрит на запад."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[2]
R = lambda n: ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', n)
B = lambda n: ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', n)
W, H = 1800, 1150
im = Image.new('RGB', (W, H), 'white'); d = ImageDraw.Draw(im)
d.text((30, 15), "План первого этажа — утверждён автором 08.10.2026", fill='black', font=B(28))
d.text((30, 55), "север — вверх; все проходы и двери — по утверждённой топологии", fill=(90, 90, 90), font=R(17))
WALL = 8
def room(x0, y0, x1, y1, fill, title, sub=''):
    d.rectangle((x0, y0, x1, y1), fill=fill, outline='black', width=WALL)
    d.text((x0 + 18, y0 + 14), title, fill='black', font=B(22))
    yy = y0 + 46
    for line in sub.split('\n'):
        if line: d.text((x0 + 18, yy), line, fill='black', font=R(16)); yy += 21
def gap(x0, y0, x1, y1, col='white'):
    d.rectangle((x0, y0, x1, y1), fill=col)
def door_label(x, y, t, col=(150, 0, 0)):
    d.text((x, y), t, fill=col, font=R(15))
# W4 зал (запад)
room(80, 120, 700, 760, (232, 240, 255), "W4 зал прекраснодушия",
     "мозаика с каймой (улика)\nдоска почёта, люк, архивный стол\nзеркало → решётка лифта 1908\nдверь «Служебное помещение»\n→ винтовая лестница вниз")
# вестибюль (восток)
room(700, 120, 1720, 900, (255, 248, 230), "W2 вестибюль",
     "плитка «под мрамор», колонны, витраж\nсухой каскад + индикатор, витрина\nплакат «Банный день», толпа")
# служебный коридор (юг, вдоль зала)
room(80, 760, 1000, 900, (250, 240, 250), "служебный коридор", "")
# прачечная (юг)
room(80, 900, 700, 1110, (232, 245, 240), "W3 прачечная", "")
# служебная сторона за стойкой
d.rectangle((1000, 760, 1720, 900), fill=(255, 236, 210), outline='black', width=WALL)
d.text((1020, 770), "служебная сторона (за стойкой)", fill='black', font=B(19))
# стены между вестибюлем и служебной стороной нет — границу задаёт сама стойка
gap(1004, 754, 1712, 766, (255, 236, 210))
# стойка: вдоль севера служебной зоны
d.rectangle((1000, 740, 1700, 768), fill=(160, 110, 60), outline='black', width=2)
d.text((1220, 712), "стойка Изольды", fill=(120, 70, 20), font=B(17))
# короткая тумба у западной стены, за ней — откидная доска над калиткой
d.rectangle((1000, 740, 1035, 768), fill=(120, 80, 40), outline='black', width=2)
d.rectangle((1035, 740, 1115, 768), fill=(250, 220, 120), outline=(200, 0, 0), width=3)
door_label(985, 690, "тумба | откидная доска\n+ калитка")
# арка из служебной зоны в коридор — в западной стене служебной зоны, прямо за калиткой
gap(996, 772, 1006, 860, (250, 240, 250)); door_label(915, 905, "арка (прямо за калиткой)")
# дверь коридор → зал (прямо, в конце коридора? — на северной стене коридора)
gap(300, 754, 380, 766, (250, 240, 250)); door_label(250, 725, "служебная дверь зала", (0, 60, 160))
# дверь коридор → прачечная
gap(420, 894, 500, 906, (232, 245, 240)); door_label(510, 905, "дверь «Прачечная»", (0, 120, 60))
# парадные двери зала из вестибюля
gap(694, 220, 706, 380, (255, 248, 230)); door_label(712, 230, "парадные двери зала\n(заперты: «Закрыт на время\nплановых улучшений»)")
# лифт, каскад, витрина
d.rectangle((1600, 140, 1700, 230), fill=(230, 210, 150), outline='black', width=3); d.text((1560, 240), "служебный лифт", fill='black', font=R(15))
d.ellipse((1080, 330, 1230, 460), fill=(200, 200, 190), outline='black', width=3); d.text((1110, 470), "каскад", fill='black', font=R(15))
d.rectangle((1290, 360, 1350, 430), fill=(220, 235, 250), outline='black', width=3); d.text((1270, 440), "витрина", fill='black', font=R(15))
d.text((1600, 560), "главный вход\nотеля (восток)", fill=(90, 90, 90), font=R(15))
for i, (x, y) in enumerate([(1060, 650), (1100, 680), (1150, 660), (1200, 690), (1260, 670)]):
    d.ellipse((x - 12, y - 12, x + 12, y + 12), fill=(240, 180, 170), outline='black')
d.text((1120, 610), "толпа у прохода", fill=(150, 40, 40), font=R(15))
# камера W2
cx, cy = 1640, 830
d.ellipse((cx - 14, cy - 14, cx + 14, cy + 14), fill='black'); d.text((cx - 170, cy + 22), "камера W2, 1,6 м", fill='black', font=B(15))
d.line((cx, cy, 700, 160), fill=(110, 110, 110), width=2); d.line((cx, cy, 980, 900), fill=(110, 110, 110), width=2)
d.text((1240, 560), "взгляд камеры — на запад", fill=(110, 110, 110), font=R(15))
# камера W2u (из-под юбки): гостевая сторона, перед западным концом стойки, взгляд на юг
ux, uy = 1120, 640
d.polygon([(ux - 12, uy - 12), (ux + 12, uy - 12), (ux, uy + 10)], fill=(0, 90, 170))
d.text((ux + 16, uy - 40), "камера W2u, 30 см", fill=(0, 90, 170), font=B(15))
d.line((ux, uy, 1430, 900), fill=(0, 90, 170), width=2); d.line((ux, uy, 820, 900), fill=(0, 90, 170), width=2)
d.text((ux - 120, uy - 64), "взгляд W2u — на юг (запад справа)", fill=(0, 90, 170), font=R(14))
# компас
d.text((1700, 60), "С ↑", fill='black', font=B(22))
out = ROOT / 'docs' / 'assets' / 'ground_floor_plan.png'; im.save(out); print(out)

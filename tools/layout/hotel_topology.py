#!/usr/bin/env python3
"""Схема топологии отеля (проект на утверждение автора). Вывод: docs/assets/hotel_topology.png"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[2]
F = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
FB = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
R = lambda n: ImageFont.truetype(F, n)
B = lambda n: ImageFont.truetype(FB, n)
W, H = 1900, 1300
im = Image.new('RGB', (W, H), 'white'); d = ImageDraw.Draw(im)

def box(x0, y0, x1, y1, title, sub='', fill=(240, 240, 240)):
    d.rounded_rectangle((x0, y0, x1, y1), 12, fill=fill, outline='black', width=3)
    d.text((x0 + 12, y0 + 8), title, fill='black', font=B(21))
    yy = y0 + 40
    for line in sub.split('\n'):
        if line:
            d.text((x0 + 12, yy), line, fill='black', font=R(16)); yy += 22

def arrow(p, q, label='', col=(0, 0, 0), w=4, dash=False, lx=8, ly=-24):
    (x0, y0), (x1, y1) = p, q
    if dash:
        n = int(((x1 - x0) ** 2 + (y1 - y0) ** 2) ** .5 // 18)
        for i in range(0, n, 2):
            a, b = i / n, min(1, (i + 1) / n)
            d.line((x0 + (x1 - x0) * a, y0 + (y1 - y0) * a, x0 + (x1 - x0) * b, y0 + (y1 - y0) * b), fill=col, width=w)
    else:
        d.line((x0, y0, x1, y1), fill=col, width=w)
    if label:
        d.multiline_text(((x0 + x1) / 2 + lx, (y0 + y1) / 2 + ly), label, fill=col, font=R(16))

d.text((30, 15), "Топология отеля — утверждена автором 08.10.2026", fill='black', font=B(30))
for y, t in [(70, "ЭТАЖИ НОМЕРОВ"), (330, "УРОВЕНЬ ВЕСТИБЮЛЯ"), (980, "ПОД ЗДАНИЕМ")]:
    d.text((30, y), t, fill=(120, 120, 120), font=B(19))
d.line((20, 310, W - 20, 310), fill=(200, 200, 200), width=2)
d.line((20, 960, W - 20, 960), fill=(200, 200, 200), width=2)

box(60, 110, 420, 280, "W1 номер 317", "санузел с душем внутри\nдверь → коридор этажа", (235, 245, 255))
box(520, 110, 900, 280, "Коридор этажа", "ковровая дорожка, двери номеров\nв конце — служебный лифт", (245, 245, 245))
arrow((420, 195), (520, 195), "дверь", ly=-26, lx=-20)
box(60, 370, 1060, 700, "W2 вестибюль — сторона гостей",
    "двери служебного лифта (только номера ↔ вестибюль)\nсухой каскад + индикатор, витрина со счётчиком\n"
    "плакат «Банный день», толпа, колонны, витраж\nпол — плитка «под мрамор»\n"
    "стойка Изольды: откидная доска + калитка → служебная сторона\nпарадные двери зала: «Закрыт на время плановых улучшений»", (255, 248, 230))
arrow((710, 280), (710, 370), "служебный лифт", (0, 90, 170), ly=-14)
box(60, 740, 620, 930, "W2 служебная сторона (за стойкой)",
    "телефон, мокрый круг под папкой, регламент,\nкнопка каскада, микрофон\nодна арка → служебный коридор", (255, 236, 210))
arrow((340, 700), (340, 740), "доска + калитка", (180, 0, 0), lx=12, ly=-12)
box(700, 740, 1300, 930, "Служебный коридор",
    "двери «Прачечная» (налево)\nи «Зал прекраснодушия» (прямо)\n(тексты Акта I)", (250, 240, 250))
arrow((620, 835), (700, 835), "", (120, 0, 120))
box(1380, 370, 1860, 560, "W3 прачечная", "табличка «Влажное очищение»\nбарабаны, люки, шкаф; декоративная стена —\nобшитый бывший проём; выход — в коридор", (232, 245, 240))
box(1380, 600, 1860, 930, "W4 зал прекраснодушия",
    "мозаика с каймой (улика!), доска почёта,\nлюк источника, архивный стол, стойка воды,\nзеркало → решётка лифта 1908,\n"
    "дверь «Служебное помещение» (лестница)\nпарадные двери из вестибюля —\nзаперты изнутри (гостей в зале нет)", (232, 240, 255))
arrow((1300, 780), (1380, 470), "дверь «налево»", (0, 120, 60), lx=-150, ly=-60)
arrow((1300, 870), (1380, 870), "дверь «прямо»", (0, 60, 160), lx=-60, ly=-26)
arrow((1060, 600), (1380, 680), "парадные двери — заперты", (150, 60, 60), dash=True, lx=-120, ly=-34)
box(1080, 1020, 1500, 1260, "Площадка Z12", "внизу винтовой лестницы\nинструкция 1908 года на стене\nдверь конторы (уведомление под пломбой)", (240, 240, 240))
box(560, 1020, 980, 1260, "W6 контора", "каменный уступ с журналом,\nтруба с маховиком\nединственный выход на площадку\n(сдача Акта IV, DS2)", (220, 240, 240))
box(60, 1020, 460, 1260, "W5 приёмный пункт", "стол приёма, лифт 1908 в скале,\nнижний пост «Вверхъ»\nвнутренняя дверь ↔ W6\n(боковая дверь — кладовая)", (220, 240, 240))
arrow((1620, 930), (1400, 1020), "винтовая лестница\n(человек — да, тележка — нет)", (0, 60, 160), lx=40, ly=-20)
arrow((1080, 1140), (980, 1140), "дверь", (0, 0, 0), lx=-25, ly=-26)
arrow((560, 1140), (460, 1140), "дверь", (0, 0, 0), lx=-25, ly=-26)
arrow((1460, 930), (300, 1020), "лифт 1908 (Лапидус — только под тележкой)", (170, 90, 0), dash=True, lx=-330, ly=-4)
out = ROOT / 'docs' / 'assets' / 'hotel_topology.png'
im.save(out); print(out)

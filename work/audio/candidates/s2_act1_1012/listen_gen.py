def card(fn, note):
    ext = "mp3"
    src = f"listen/{fn}.{ext}"
    tag = f'<span class="tag">{html.escape(note)}</span>' if note else ""
    return (f'<article class="card"><div class="head"><span class="name">{fn}</span>{tag}</div>'
            f'<audio controls preload="none" src="{src}"></audio></article>')



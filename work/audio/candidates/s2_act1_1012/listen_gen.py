def card(fn, note):
    src = f"{fn}.mp3" if "/" in fn else f"listen/{fn}.mp3"
    tag = f'<span class="tag">{html.escape(note)}</span>' if note else ""
    pick = '<span class="pick">выбран</span>' if fn in CHOSEN else ""
    cls = "card chosen" if fn in CHOSEN else "card"
    return (f'<article class="{cls}"><div class="head"><span class="name">{fn.split("/")[-1]}</span>{tag}{pick}</div>'
            f'<audio controls preload="none" src="{src}"></audio></article>')



    cards = "\n".join(card(f, n) for f, n in items)
    parts.append(f'<section><h2>{html.escape(title)}</h2><div class="moment"><p><b>{name}.</b> {html.escape(moment)}</p></div>'
                 f'<div class="grid">{cards}</div></section>')

